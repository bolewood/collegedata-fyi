import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import {
  WAITLIST_ANALYSIS_ROWS,
  WAITLIST_ANALYSIS_SUMMARY,
  WAITLIST_REPORTED_ANOMALY_ROWS,
} from "./waitlist-recipe-analysis";
import { WAITLIST_RECIPE_SUMMARY, WAITLIST_ROWS } from "./waitlist-recipe-data";

describe("waitlist recipe identity", () => {
  it("keeps Tufts CDS values attached to the Tufts federal identity", () => {
    const tufts = WAITLIST_ROWS.find(
      (row) => row.documentId === "7a5bb196-7973-4f7f-87c1-adc699248073",
    );

    expect(tufts).toMatchObject({
      ipedsId: "168148",
      schoolId: "tufts",
      schoolName: "Tufts University",
      state: "MA",
      control: "Private nonprofit",
      carnegie: "Doctoral universities",
      undergradEnrollment: 7061,
      schoolUrl: "/schools/tufts/2024-25",
    });
  });
});

describe("waitlist recipe snapshot", () => {
  const dataFile = readFileSync(join(process.cwd(), "src/lib/waitlist-recipe-data.ts"), "utf8");
  const doc = readFileSync(join(process.cwd(), "..", "docs/recipes/waitlist-odds.md"), "utf8");

  it("carries the generated header and a parseable generated-at date", () => {
    expect(dataFile.startsWith("// Generated by tools/scorecard/build_waitlist_recipe.py.")).toBe(true);
    expect(dataFile).toContain(`// Generated at ${WAITLIST_RECIPE_SUMMARY.generatedAt}.`);
    const stamp = WAITLIST_RECIPE_SUMMARY.generatedAt;
    expect(stamp).toMatch(/^\d{4}-\d{2}-\d{2}$/);
    const parsed = new Date(`${stamp}T00:00:00Z`);
    expect(Number.isNaN(parsed.getTime())).toBe(false);
    expect(parsed.toISOString().slice(0, 10)).toBe(stamp);
    expect(parsed.getTime()).toBeLessThanOrEqual(Date.now() + 24 * 60 * 60 * 1000);
  });

  it("is internally consistent", () => {
    const ids = new Set<string>();
    for (const row of WAITLIST_ROWS) {
      expect(ids.has(row.documentId), `duplicate document ${row.documentId}`).toBe(false);
      ids.add(row.documentId);
      expect(row.year).toMatch(/^\d{4}-\d{2}$/);
      expect(Number(row.year.slice(0, 4))).toBe(row.yearStart);
      expect(Number(row.year.slice(5))).toBe((row.yearStart + 1) % 100);
      expect(row.schoolUrl).toBe(`/schools/${row.schoolId}/${row.year}`);
      expect(
        [row.waitListOffered, row.waitListAccepted, row.waitListAdmitted].some((v) => v != null),
        `${row.schoolId} ${row.year} has no wait-list count`,
      ).toBe(true);
      const { waitListOffered: o, waitListAccepted: a, waitListAdmitted: d } = row;
      if (o != null && a != null) expect(a, `${row.schoolId} ${row.year}`).toBeLessThanOrEqual(o);
      if (a != null && d != null) expect(d, `${row.schoolId} ${row.year}`).toBeLessThanOrEqual(a);
      expect(row.complete).toBe(o != null && a != null && d != null);
    }
    const complete = WAITLIST_ROWS.filter((r) => r.complete && (r.waitListAccepted ?? 0) > 0);
    expect(WAITLIST_RECIPE_SUMMARY.allVisibleRows).toBe(WAITLIST_ROWS.length);
    expect(WAITLIST_RECIPE_SUMMARY.completeRows).toBe(complete.length);
    expect(WAITLIST_RECIPE_SUMMARY.partialRows).toBe(WAITLIST_ROWS.length - complete.length);
    expect(WAITLIST_RECIPE_SUMMARY.completeSchools).toBe(new Set(complete.map((r) => r.schoolId)).size);
  });

  it("matches the numbers quoted in docs/recipes/waitlist-odds.md", () => {
    const s = WAITLIST_ANALYSIS_SUMMARY;
    const pct = (v: number | null, places: number) => `${((v ?? 0) * 100).toFixed(places)}%`;
    expect(doc).toContain(
      `${s.completeRows} complete school-year rows across ${WAITLIST_RECIPE_SUMMARY.completeSchools} schools, plus ${s.partialRows} partial rows`,
    );
    expect(doc).toContain(
      `${WAITLIST_REPORTED_ANOMALY_ROWS.length} high-volume near-total rows are flagged as reported anomalies, leaving ${WAITLIST_ANALYSIS_ROWS.length} school-year rows across ${s.analysisSchools} schools`,
    );
    expect(doc).toContain(`median success rate among accepted wait-list spots: ${pct(s.medianSuccessRate, 0)}`);
    expect(doc).toContain(`weighted success rate: ${pct(s.weightedSuccessRate, 0)}`);
    expect(doc).toContain(`rate: ${pct(s.medianOfferSuccessRate, 1)}\n`);
    expect(doc).toContain(`rows under 2% success: ${s.zeroishRows}`);
  });
});
